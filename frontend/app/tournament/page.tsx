import type { Metadata } from "next";
import Link from "next/link";

import { apiGet } from "@/lib/api";
import { ArenaHero } from "@/components/tournament/ArenaHero";
import { ArenaLoader } from "@/components/tournament/ArenaLoader";
import { CollegeWall } from "@/components/tournament/CollegeWall";
import { EventDetails } from "@/components/tournament/EventDetails";
import { PrizePool } from "@/components/tournament/PrizePool";
import { Reveal } from "@/components/Reveal";
import { SponsorWall } from "@/components/tournament/SponsorWall";
import { TournamentFAQ } from "@/components/tournament/TournamentFAQ";
import { TournamentTimeline } from "@/components/tournament/TournamentTimeline";
import { SITE_URL } from "@/lib/constants";
import {
  DEFAULT_TOURNAMENT_CONFIG,
  TOURNAMENT_NAME,
  formatINR,
  type Announcement,
  type College,
  type Sponsor,
  type TournamentConfig,
} from "@/lib/tournament";

const TITLE = `${TOURNAMENT_NAME} — Mumbai's trading competition`;
const DESCRIPTION =
  "Quantrelic's Mumbai Trading Tournament — a competitive trading event for college students across Mumbai. Individual participation, college-level qualifying rounds, and a ₹1,00,000 prize pool.";

export const metadata: Metadata = {
  title: { absolute: TITLE },
  description: DESCRIPTION,
  openGraph: {
    type: "website",
    title: TITLE,
    description: DESCRIPTION,
    url: `${SITE_URL}/tournament`,
    // og:image is generated by app/tournament/opengraph-image.tsx
  },
  twitter: { card: "summary_large_image", title: TITLE, description: DESCRIPTION },
  alternates: { canonical: `${SITE_URL}/tournament` },
};

export const revalidate = 120;

export default async function TournamentPage() {
  const [config, colleges, sponsors, announcements] = await Promise.all([
    apiGet<TournamentConfig>("/api/v1/tournament", DEFAULT_TOURNAMENT_CONFIG),
    apiGet<{ colleges: College[] }>("/api/v1/tournament/colleges", { colleges: [] }),
    apiGet<{ sponsors: Sponsor[] }>("/api/v1/tournament/sponsors", { sponsors: [] }),
    apiGet<{ announcements: Announcement[] }>("/api/v1/tournament/announcements", {
      announcements: [],
    }),
  ]);

  return (
    <>
      {/* Cinematic intro — once per session, skippable, reduced-motion aware. */}
      <ArenaLoader />

      <script
        type="application/ld+json"
        dangerouslySetInnerHTML={{
          __html: JSON.stringify({
            "@context": "https://schema.org",
            "@type": "Event",
            name: config.name,
            alternateName: config.short_name,
            description: config.hero_subhead || DESCRIPTION,
            url: `${SITE_URL}/tournament`,
            organizer: { "@type": "Organization", name: config.organizer },
            eventAttendanceMode: "https://schema.org/OfflineEventAttendanceMode",
            ...(config.event_starts_at ? { startDate: config.event_starts_at } : {}),
            ...(config.venue
              ? { location: { "@type": "Place", name: config.venue, address: config.location_context } }
              : { location: { "@type": "Place", addressLocality: config.location_context } }),
          }),
        }}
      />

      <ArenaHero config={config} />
      <TournamentTimeline config={config} />
      <PrizePool config={config} />
      <CollegeWall colleges={colleges.colleges} />
      <SponsorWall sponsors={sponsors.sponsors} />

      {announcements.announcements.length > 0 && (
        <section className="border-t border-white/8 bg-arena-900 py-16">
          <div className="mx-auto max-w-7xl px-4 sm:px-6">
            <p className="font-mono text-[10px] uppercase tracking-[0.3em] text-flare-300">
              Announcements
            </p>
            <ul className="mt-6 grid gap-4 lg:grid-cols-3">
              {announcements.announcements.slice(0, 3).map((announcement) => (
                <li
                  key={announcement.id}
                  className="arena-panel arena-panel-sm border-l-2 border-l-flare-500/60 p-5"
                >
                  <p className="font-display text-base font-semibold text-bone">
                    {announcement.title}
                  </p>
                  <p className="mt-2 whitespace-pre-line text-sm leading-relaxed text-ash">
                    {announcement.body_md}
                  </p>
                </li>
              ))}
            </ul>
          </div>
        </section>
      )}

      <EventDetails config={config} />

      <section className="border-t border-white/8 bg-arena-900 py-20">
        <div className="mx-auto max-w-3xl px-4 sm:px-6">
          <TournamentFAQ config={config} />
          <div className="mt-8 text-center">
            <Link
              href="/tournament/faq"
              className="arena-focus rounded font-mono text-[11px] uppercase tracking-[0.22em] text-flare-300 underline underline-offset-4"
            >
              Read every frequently asked question
            </Link>
          </div>
        </div>
      </section>

      {/* Closing CTA */}
      <section className="relative overflow-hidden border-t border-white/8 bg-arena-950 py-24">
        <div
          aria-hidden="true"
          className="pointer-events-none absolute left-1/2 top-0 h-[32rem] w-[52rem] -translate-x-1/2 opacity-50"
          style={{
            background:
              "radial-gradient(ellipse at center, rgba(244,124,53,0.22), transparent 65%)",
          }}
        />
        <div className="relative mx-auto max-w-4xl px-4 text-center sm:px-6">
          <Reveal>
            <p className="font-mono text-[10px] uppercase tracking-[0.32em] text-flare-300">
              {formatINR(config.prize_pool_total)} prize pool · {config.participation_type}{" "}
              participation
            </p>
            <h2 className="mt-6 font-display text-4xl font-semibold uppercase leading-[0.98] tracking-tightest text-bone sm:text-6xl">
              Take your position
              <br />
              in the arena.
            </h2>
            <p className="mx-auto mt-6 max-w-xl text-[15px] leading-relaxed text-ash">
              Register individually, represent your college, and compete with the sharpest student
              traders across Mumbai.
            </p>
            <div className="mt-10 flex flex-col items-center justify-center gap-3 sm:flex-row">
              <Link href="/tournament/register" className="btn-flare arena-focus rounded-full px-8 py-4 text-base">
                Register now
              </Link>
              <Link href="/tournament/leaderboard" className="btn-ghost arena-focus rounded-full px-8 py-4 text-base">
                View leaderboard
              </Link>
            </div>
          </Reveal>
        </div>
      </section>
    </>
  );
}
